create table if not exists browse_entry (
    id varchar(64) primary key,
    datasource varchar(128) not null,
    database_name varchar(128) not null,
    schema_name varchar(128) not null,
    tables_json varchar(4000) not null,
    include_columns_json varchar(4000),
    exclude_columns_json varchar(4000),
    mask_columns_json varchar(4000),
    row_policy varchar(1000),
    subjects_json varchar(2000),
    page_size int not null default 200,
    max_rows int not null default 5000,
    export_enabled boolean not null default false,
    status varchar(16) not null default 'PENDING',
    valid_until date,
    applicant varchar(128),
    approved_by varchar(128),
    created_at timestamp not null,
    updated_at timestamp not null
);

create table if not exists approval_event (
    id bigint generated by default as identity primary key,
    entry_id varchar(64) not null,
    action varchar(16) not null,
    actor varchar(128) not null,
    comment varchar(1000),
    created_at timestamp not null
);

create table if not exists audit_event (
    id bigint generated by default as identity primary key,
    event_time timestamp not null,
    username varchar(128) not null,
    action varchar(16) not null,
    target varchar(512),
    detail_json varchar(4000),
    result_code int,
    duration_ms bigint,
    client_ip varchar(64)
);

create table if not exists user_attr (
    username varchar(128) not null,
    attr_key varchar(64) not null,
    attr_value varchar(512),
    primary key (username, attr_key)
);

create table if not exists key_mapping (
    id bigint generated by default as identity primary key,
    target_fqn varchar(512) not null,
    key_column varchar(128) not null,
    source_fqn varchar(512) not null,
    source_key_column varchar(128) not null,
    maintained_by varchar(128),
    created_at timestamp not null,
    unique (target_fqn, key_column, source_fqn)
);

create table if not exists row_switch (
    table_fqn varchar(512) primary key,
    enabled boolean not null default false,
    updated_by varchar(128),
    updated_at timestamp not null
);

create index if not exists idx_browse_status on browse_entry (status);
create index if not exists idx_audit_time on audit_event (event_time);

-- lineage actions (KEY_MAPPING_WRITE, ...) exceed the original 16-char width
alter table audit_event alter column action varchar(32);
